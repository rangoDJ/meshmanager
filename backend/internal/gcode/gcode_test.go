const prusaStyle = `; generated by PrusaSlicer 2.8.1 on 2026-10-19
G21 ; mm
G90
M83 ; relative extrusion
G28
G1 Z0.2 F600
G1 X10 Y10 F3000         ; travel to start
;TYPE:Skirt/Brim
G1 X20 Y10 E0.5
;TYPE:External perimeter
G1 X20 Y20 E0.5
G1 X10 Y20 E0.5
;TYPE:Solid infill
G1 X10 Y10 E0.5
G1 E-0.8                 ; retract (no move)
G1 Z0.4                  ; next layer
G1 X15 Y15               ; travel
;TYPE:Perimeter
G2 X25 Y15 I5 J0 E1.2    ; half-circle arc, clockwise
;TYPE:Support material
G1 X25 Y25 E0.3
; filament used [mm] = 1234.56
; filament used [g] = 3.71
; estimated printing time (normal mode) = 1h 2m 3s
`

func TestParsePrusaStyle(t *testing.T) {
	tp, err := Parse(strings.NewReader(prusaStyle))
	if err != nil {
		t.Fatal(err)
	}
	if len(tp.Layers) != 2 {
		t.Fatalf("layers: %+v", tp.Layers)
	}
	l0, l1 := tp.Layers[0], tp.Layers[1]
	if math.Abs(l0.Z-0.2) > 1e-9 || math.Abs(l1.Z-0.4) > 1e-9 || math.Abs(l1.Height-0.2) > 1e-9 {
		t.Errorf("layer heights: %+v", tp.Layers)
	}
	if l0.ExtrusionCount != 4 {
		t.Errorf("layer 0 extrusions: %d, want 4", l0.ExtrusionCount)
	}
	// Layer 1: arc (several chords) + one support line; one travel before the arc.
	if l1.ExtrusionCount < 4 || l1.TravelCount != 1 {
		t.Errorf("layer 1: %+v", l1)
	}
	// The initial travel before any extrusion isn't drawn.
	if l0.TravelCount != 0 {
		t.Errorf("layer 0 travels: %d", l0.TravelCount)
	}

	want0 := []uint8{featSkirt, featOuterWall, featOuterWall, featSolidInfill}
	for i, f := range want0 {
		if tp.Feature[i] != f {
			t.Errorf("segment %d feature %s, want %s", i, Features[tp.Feature[i]], Features[f])
		}
	}
	if tp.Feature[l1.ExtrusionStart] != featInnerWall || tp.Feature[len(tp.Feature)-1] != featSupport {
		t.Errorf("layer 1 features: %v", tp.Feature[l1.ExtrusionStart:])
	}

	// G-code's Y points up, so the clockwise half circle from (15,15) to (25,15) around
	// (20,15) passes over the top, through y=20.
	maxY := math.Inf(-1)
	for i := l1.ExtrusionStart; i < l1.ExtrusionStart+l1.ExtrusionCount-1; i++ {
		maxY = math.Max(maxY, float64(tp.Extrusions[i*4+3]))
	}
	if math.Abs(maxY-20) > 0.05 {
		t.Errorf("arc highest point %v, want ~20", maxY)
	}

	if tp.Slicer != "PrusaSlicer 2.8.1 on 2026-10-19" || tp.PrintSeconds != 3723 ||
		tp.FilamentGrams != 3.71 || tp.FilamentMM != 1234.56 {
		t.Errorf("metadata: slicer=%q time=%v g=%v mm=%v", tp.Slicer, tp.PrintSeconds, tp.FilamentGrams, tp.FilamentMM)
	}
	if tp.Max[0] != 25 || tp.Max[2] != 0.4 || tp.Min[0] != 10 {
		t.Errorf("bounds %v..%v", tp.Min, tp.Max)
	}
}

func TestParseBambuAndAbsoluteE(t *testing.T) {
	g := `; HEADER_BLOCK_START
; BambuStudio 01.10.00.89
; model printing time: 52m 10s; total estimated time: 58m 39s
; total filament weight [g] : 12.5
; HEADER_BLOCK_END
M82 ; absolute extrusion
G92 E0
G1 Z.2
G1 X0 Y0
; FEATURE: Outer wall
G1 X5 Y0 E1
G1 X5 Y5 E2
G92 E0
; FEATURE: Sparse infill
G1 X0 Y5 E0.5
G1 X0 Y0 E0.5            ; E unchanged: a travel, not an extrusion
`
	tp, err := Parse(strings.NewReader(g))
	if err != nil {
		t.Fatal(err)
	}
	if len(tp.Feature) != 3 || tp.Feature[0] != featOuterWall || tp.Feature[2] != featInfill {
		t.Fatalf("features: %v", tp.Feature)
	}
	if len(tp.Travels)/4 != 1 {
		t.Errorf("travels: %d, want 1", len(tp.Travels)/4)
	}
	if tp.PrintSeconds != 58*60+39 || tp.FilamentGrams != 12.5 {
		t.Errorf("metadata: time=%v g=%v", tp.PrintSeconds, tp.FilamentGrams)
	}
}

func TestParseCuraInches(t *testing.T) {
	g := ";FLAVOR:Marlin\n;TIME:600\n;Filament used: 2.5m\nG20\nM83\nG1 Z0.01\nG1 X1 Y0\n;TYPE:WALL-OUTER\nG1 X2 Y0 E0.1\n"
	tp, err := Parse(strings.NewReader(g))
	if err != nil {
		t.Fatal(err)
	}
	if tp.Slicer != "Cura" || tp.PrintSeconds != 600 || tp.FilamentMM != 2500 {
		t.Errorf("metadata: %q %v %v", tp.Slicer, tp.PrintSeconds, tp.FilamentMM)
	}
	if x := tp.Extrusions[2]; math.Abs(float64(x)-50.8) > 1e-3 || tp.Feature[0] != featOuterWall {
		t.Errorf("inch conversion: x2=%v feature=%d", x, tp.Feature[0])
	}
}

func TestParseRejectsNonGCode(t *testing.T) {
	if _, err := Parse(strings.NewReader("hello\nworld\n")); err == nil {
		t.Error("expected an error for a file without extrusion")
	}
}
