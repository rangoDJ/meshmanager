func pngOf(w, h int, c color.NRGBA) []byte {
	img := image.NewNRGBA(image.Rect(0, 0, w, h))
	for y := range h {
		for x := range w {
			img.SetNRGBA(x, y, c)
		}
	}
	var b bytes.Buffer
	_ = png.Encode(&b, img)
	return b.Bytes()
}

func write(t *testing.T, name string, data []byte) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(p, data, 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func gcodeThumb(w, h int, c color.NRGBA, tag string) string {
	b64 := base64.StdEncoding.EncodeToString(pngOf(w, h, c))
	var s strings.Builder
	s.WriteString("; " + tag + " begin " + "x 0\n")
	for len(b64) > 0 {
		n := min(78, len(b64))
		s.WriteString("; " + b64[:n] + "\n")
		b64 = b64[n:]
	}
	s.WriteString("; " + tag + " end\n")
	return s.String()
}

func TestGCodePreviewPicksLargest(t *testing.T) {
	gcode := "; generated by OrcaSlicer\n;\n" +
		gcodeThumb(16, 16, color.NRGBA{255, 0, 0, 255}, "thumbnail") +
		gcodeThumb(64, 48, color.NRGBA{0, 0, 255, 255}, "thumbnail_PNG") +
		"G28\nG1 X10 Y10\n"
	res, err := Generate(write(t, "part.gcode", []byte(gcode)), "gcode", 384)
	if err != nil {
		t.Fatal(err)
	}
	b := res.Image.Bounds()
	if b.Dx() != 64 || b.Dy() != 48 || res.Origin != OriginEmbedded {
		t.Fatalf("got %v from %s", b, res.Origin)
	}
	if r, _, bl, _ := res.Image.At(1, 1).RGBA(); bl < r {
		t.Error("expected the blue (larger) thumbnail")
	}

	if _, err := Generate(write(t, "plain.gcode", []byte("G28\n")), "gcode", 384); err != errNoPreview {
		t.Errorf("G-code without a thumbnail: %v", err)
	}
}

func TestFreeCADPreview(t *testing.T) {
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	w, _ := zw.Create("Document.xml")
	_, _ = w.Write([]byte("<Document/>"))
	w, _ = zw.Create("thumbnails/Thumbnail.png")
	_, _ = w.Write(pngOf(128, 128, color.NRGBA{0, 200, 0, 255}))
	_ = zw.Close()
	res, err := Generate(write(t, "bracket.FCStd", buf.Bytes()), "fcstd", 384)
	if err != nil || res.Image.Bounds().Dx() != 128 {
		t.Fatalf("FCStd preview: %v %v", err, res.Image)
	}
}

func TestLightBurnPreview(t *testing.T) {
	b64 := base64.StdEncoding.EncodeToString(pngOf(200, 100, color.NRGBA{10, 10, 10, 255}))
	project := `<?xml version="1.0" encoding="UTF-8"?>
<LightBurnProject AppVersion="1.7.00" FormatVersion="1">
    <Thumbnail Source="` + b64 + `"/>
    <CutSetting type="Cut"/>
</LightBurnProject>`
	res, err := Generate(write(t, "sign.lbrn2", []byte(project)), "lbrn", 384)
	if err != nil || res.Image.Bounds().Dx() != 200 || res.Image.Bounds().Dy() != 100 {
		t.Fatalf("LightBurn preview: %v", err)
	}
	if _, err := Generate(write(t, "old.lbrn", []byte("<LightBurnProject/>")), "lbrn", 384); err != errNoPreview {
		t.Errorf("LightBurn without a preview: %v", err)
	}
}

func TestSVGRasterize(t *testing.T) {
	svg := `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 100">
  <script>alert(1)</script>
  <rect x="0" y="0" width="200" height="100" fill="#ff0000"/>
</svg>`
	res, err := Generate(write(t, "cut.svg", []byte(svg)), "svg", 256)
	if err != nil {
		t.Fatal(err)
	}
	b := res.Image.Bounds()
	if b.Dx() != 256 || b.Dy() != 128 {
		t.Fatalf("size %v, want 256x128 (aspect kept)", b)
	}
	r, g, _, a := res.Image.At(128, 64).RGBA()
	if a == 0 || r < 0xf000 || g > 0x1000 {
		t.Errorf("centre pixel not red: %v", res.Image.At(128, 64))
	}

	// Line art on nothing gets a white ground.
	lines := `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><path d="M1 1 L9 9" stroke="black"/></svg>`
	res, err = Generate(write(t, "lines.svg", []byte(lines)), "svg", 64)
	if err != nil {
		t.Fatal(err)
	}
	if r, g, b, a := res.Image.At(60, 2).RGBA(); a != 0xffff || r != 0xffff || g != 0xffff || b != 0xffff {
		t.Errorf("background pixel not white: %v", res.Image.At(60, 2))
	}
}

// A .gltf with its buffer embedded as a data URI renders like a GLB.
func TestGLTFEmbedded(t *testing.T) {
	// One triangle, 10 mm, in metres, Y-up.
	pos := []float32{0, 0, 0, 0.01, 0, 0, 0, 0.01, 0}
	var bin bytes.Buffer
	for _, f := range pos {
		_ = binary.Write(&bin, binary.LittleEndian, math.Float32bits(f))
	}
	doc := map[string]any{
		"asset":       map[string]any{"version": "2.0"},
		"scene":       0,
		"scenes":      []any{map[string]any{"nodes": []int{0}}},
		"nodes":       []any{map[string]any{"mesh": 0}},
		"meshes":      []any{map[string]any{"primitives": []any{map[string]any{"attributes": map[string]int{"POSITION": 0}}}}},
		"buffers":     []any{map[string]any{"byteLength": bin.Len(), "uri": "data:application/octet-stream;base64," + base64.StdEncoding.EncodeToString(bin.Bytes())}},
		"bufferViews": []any{map[string]any{"buffer": 0, "byteLength": bin.Len()}},
		"accessors":   []any{map[string]any{"bufferView": 0, "componentType": 5126, "count": 3, "type": "VEC3", "min": []float32{0, 0, 0}, "max": []float32{0.01, 0.01, 0}}},
	}
	js, _ := json.Marshal(doc)
	res, err := Generate(write(t, "tri.gltf", js), "gltf", 64)
	if err != nil {
		t.Fatal(err)
	}
	if res.Stats == nil || res.Stats.Triangles != 1 || res.Origin != OriginRendered {
		t.Fatalf("gltf: %+v", res)
	}
}
