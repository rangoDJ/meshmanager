const slicedCube = `; generated by OrcaSlicer 2.2.0
; total estimated time: 12m 30s
; total filament weight [g] : 2.5
M83
G1 Z0.2
G1 X0 Y0
; FEATURE: Outer wall
G1 X10 Y0 E0.5
G1 X10 Y10 E0.5
; FEATURE: Sparse infill
G1 X0 Y10 E0.5
G1 Z0.4
G1 X0 Y0
; FEATURE: Outer wall
G1 X10 Y0 E0.5
`

func TestToolpathEndpoint(t *testing.T) {
	cfg := testConfig(t)
	base, st := newServerWithConfig(t, cfg)
	c := newClient(t, base)
	setupAdmin(t, c)
	startWorker(t, st, cfg)

	lib := filepath.Join(cfg.LibraryRoot, "lib")
	writeLibFile(t, lib, "Sliced/cube_PLA_12m.gcode", []byte(slicedCube))
	writeLibFile(t, lib, "cube.stl", cubeSTL(10))
	_, src := c.do("POST", "/api/sources", map[string]any{"path": "lib"})
	waitForScan(t, c, src["id"])

	items, _ := listFiles(t, c, "kind=gcode")
	if len(items) != 1 || items[0]["kind"] != "gcode" {
		t.Fatalf("gcode files: %v", names(items))
	}
	path := fmt.Sprintf("/api/files/%v/toolpath", items[0]["id"])
	status, h, body := c.raw(path)
	if status != 200 || string(body[:4]) != "MMT1" {
		t.Fatalf("toolpath: %d %q", status, body[:min(len(body), 4)])
	}

	n := int(binary.LittleEndian.Uint32(body[4:8]))
	var header struct {
		Layers []struct {
			Z              float64 `json:"z"`
			ExtrusionCount int     `json:"extrusion_count"`
			TravelCount    int     `json:"travel_count"`
		} `json:"layers"`
		Features      []string `json:"features"`
		Extrusions    int      `json:"extrusions"`
		Travels       int      `json:"travels"`
		Slicer        string   `json:"slicer"`
		PrintSeconds  float64  `json:"print_seconds"`
		FilamentGrams float64  `json:"filament_grams"`
	}
	if err := json.Unmarshal(body[8:8+n], &header); err != nil {
		t.Fatal(err)
	}
	if len(header.Layers) != 2 || header.Layers[0].ExtrusionCount != 3 || header.Layers[1].TravelCount != 1 {
		t.Errorf("layers: %+v", header.Layers)
	}
	if header.Extrusions != 4 || header.Travels != 1 {
		t.Errorf("counts: extrusions=%d travels=%d", header.Extrusions, header.Travels)
	}
	if header.Slicer != "OrcaSlicer 2.2.0" || header.PrintSeconds != 750 || header.FilamentGrams != 2.5 || len(header.Features) < 5 {
		t.Errorf("metadata: %+v", header)
	}
	// Payload: floats for extrusions and travels, then one feature byte each, padded.
	want := 8 + n + (header.Extrusions+header.Travels)*16 + (header.Extrusions+3)/4*4
	if len(body) != want {
		t.Errorf("payload length %d, want %d", len(body), want)
	}

	req, _ := http.NewRequest("GET", base+path, nil)
	req.Header.Set("If-None-Match", h.Get("ETag"))
	resp, err := c.http.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	resp.Body.Close()
	if resp.StatusCode != http.StatusNotModified {
		t.Errorf("revalidate: %d", resp.StatusCode)
	}

	models, _ := listFiles(t, c, "kind=model")
	if status, _ := c.do("GET", fmt.Sprintf("/api/files/%v/toolpath", models[0]["id"]), nil); status != 404 {
		t.Errorf("toolpath of an STL: %d, want 404", status)
	}
}

// decodeToolpath splits an MMT1 response into its header JSON.
func decodeToolpath(t *testing.T, body []byte) (h struct {
	Layers        []struct{} `json:"layers"`
	Extrusions    int        `json:"extrusions"`
	Slicer        string     `json:"slicer"`
	PrintSeconds  float64    `json:"print_seconds"`
	FilamentGrams float64    `json:"filament_grams"`
	FilamentMM    float64    `json:"filament_mm"`
	Plates        []int      `json:"plates"`
	Plate         int        `json:"plate"`
	Max           [3]float64 `json:"max"`
}) {
	t.Helper()
	if len(body) < 8 || string(body[:4]) != "MMT1" {
		t.Fatalf("not a toolpath: %q", body[:min(len(body), 80)])
	}
	n := int(binary.LittleEndian.Uint32(body[4:8]))
	if err := json.Unmarshal(body[8:8+n], &h); err != nil {
		t.Fatal(err)
	}
	return h
}

// plateGCode is a one-or-two layer print whose square is size mm wide; it carries no
// time or filament comments, like the files Bambu Studio exports.
func plateGCode(size int, layers int) []byte {
	s := "; BambuStudio\nM83\n"
	for l := 1; l <= layers; l++ {
		s += fmt.Sprintf("G1 Z%.1f\nG1 X0 Y0\n; FEATURE: Outer wall\nG1 X%d Y0 E0.5\nG1 X%d Y%d E0.5\n", float64(l)*0.2, size, size, size)
	}
	return []byte(s)
}

const sliceInfo = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header><header_item key="X-BBL-Client-Type" value="slicer"/></header>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="3600"/>
    <metadata key="weight" value="12.5"/>
    <filament id="1" type="PLA" used_m="4.2" used_g="12.5"/>
  </plate>
  <plate>
    <metadata key="index" value="2"/>
    <metadata key="prediction" value="90"/>
    <filament id="1" type="PLA" used_m="1.5" used_g="4.5"/>
  </plate>
</config>`

func TestGCode3MFPlates(t *testing.T) {
	cfg := testConfig(t)
	base, st := newServerWithConfig(t, cfg)
	c := newClient(t, base)
	setupAdmin(t, c)
	startWorker(t, st, cfg)

	var pngBuf bytes.Buffer
	img := image.NewNRGBA(image.Rect(0, 0, 24, 24))
	_ = png.Encode(&pngBuf, img)
	sliced := zipBytes(t, map[string][]byte{
		"3D/3dmodel.model":           []byte("<model/>"),
		"Metadata/plate_1.gcode":     plateGCode(10, 2),
		"Metadata/plate_2.gcode":     plateGCode(40, 3),
		"Metadata/plate_1.gcode.md5": []byte("abc"),
		"Metadata/plate_1.png":       pngBuf.Bytes(),
		"Metadata/slice_info.config": []byte(sliceInfo),
	})

	lib := filepath.Join(cfg.LibraryRoot, "lib")
	writeLibFile(t, lib, "Sliced/box.gcode.3mf", sliced)
	writeLibFile(t, lib, "Packs/bundle.zip", zipBytes(t, map[string][]byte{"inner.gcode.3mf": sliced}))
	_, src := c.do("POST", "/api/sources", map[string]any{"path": "lib"})
	waitForScan(t, c, src["id"])

	items, _ := listFiles(t, c, "kind=gcode")
	if len(items) != 2 {
		t.Fatalf("gcode files: %s", names(items))
	}
	for _, it := range items {
		if it["format"] != "gcode3mf" || it["viewable"] != false {
			t.Errorf("%v: format=%v viewable=%v", it["name"], it["format"], it["viewable"])
		}
		// The embedded plate render is the thumbnail.
		thumb := fmt.Sprintf("/api/files/%v/thumbnail", it["id"])
		var status int
		for deadline := time.Now().Add(20 * time.Second); time.Now().Before(deadline); time.Sleep(100 * time.Millisecond) {
			if status, _, _ = c.raw(thumb); status != http.StatusAccepted {
				break
			}
		}
		if status != 200 {
			t.Errorf("%v thumbnail: %d", it["name"], status)
		}

		path := fmt.Sprintf("/api/files/%v/toolpath", it["id"])
		status, h1, body := c.raw(path)
		if status != 200 {
			t.Fatalf("%v toolpath: %d %s", it["name"], status, body)
		}
		h := decodeToolpath(t, body)
		if len(h.Layers) != 2 || h.Plate != 1 || !slices.Equal(h.Plates, []int{1, 2}) || h.Max[0] != 10 {
			t.Errorf("plate 1: layers=%d plate=%d plates=%v maxX=%v", len(h.Layers), h.Plate, h.Plates, h.Max[0])
		}
		// The G-code has no estimates; slice_info.config supplies them.
		if h.PrintSeconds != 3600 || h.FilamentGrams != 12.5 || h.FilamentMM != 4200 {
			t.Errorf("plate 1 estimates: %v s, %v g, %v mm", h.PrintSeconds, h.FilamentGrams, h.FilamentMM)
		}

		status, h2, body := c.raw(path + "?plate=2")
		if status != 200 {
			t.Fatalf("plate 2: %d %s", status, body)
		}
		h = decodeToolpath(t, body)
		if len(h.Layers) != 3 || h.Plate != 2 || h.Max[0] != 40 || h.PrintSeconds != 90 || h.FilamentGrams != 4.5 {
			t.Errorf("plate 2: %+v", h)
		}
		if h1.Get("ETag") == h2.Get("ETag") {
			t.Error("plates share an ETag")
		}
		if status, _, _ := c.raw(path + "?plate=3"); status != 404 {
			t.Errorf("missing plate: %d, want 404", status)
		}
		if status, _, _ := c.raw(path + "?plate=x"); status != 400 {
			t.Errorf("bad plate: %d, want 400", status)
		}
	}
}
